# Generates src/stubs.rs from the bindgen output: one trivial callback per interface member
# that lib.rs does not write by hand, plus the static interface tables.
import re, sys
s = open(sys.argv[1]).read()
HAND = set("destroyDocumentController getFactory createAudioSource updateAudioSourceProperties enableAudioSourceSamplesAccess destroyAudioSource isAudioSourceContentAvailable isAudioSourceContentAnalysisIncomplete requestAudioSourceContentAnalysis getAudioSourceContentGrade createAudioSourceContentReader getContentReaderEventCount getContentReaderDataForEvent destroyContentReader isLicensedForCapabilities createAudioModification cloneAudioModification destroyAudioModification createPlaybackRegion updatePlaybackRegionProperties destroyPlaybackRegion".split())
TRUE = {"restoreObjectsFromArchive", "storeObjectsToArchive"}
def members(name):
    i = s.index(f"pub struct {name} {{"); j = s.index("\n}\n", i); body = s[i:j]
    out = []
    for p in re.split(r'\n\s*pub ', body)[1:]:
        p = ' '.join(p.split())
        n = p.split(':')[0]
        if n == 'structSize': continue
        m = re.match(r'\w+: ::std::option::Option<\s*unsafe extern "C" fn\((.*?)\)(?: -> (.*?))?,?\s*>,?$', p)
        assert m, p
        args = [a.strip() for a in m.group(1).split(',') if a.strip()]
        out.append((n, args, m.group(2)))
    return out
def default(n, ret):
    if ret is None: return ""
    if n in TRUE: return "1"
    if ret.endswith("Ref"): return f"Box::into_raw(Box::new(0u64)) as {ret}"
    if ret.startswith("*const") or ret.startswith("*mut"): return "std::ptr::null_mut::<u8>() as _"
    return "0"
out = ["// GENERATED by gen_stubs.py, do not edit.\n"]
count = 0
for st, pre, hand in [("ARADocumentControllerInterface", "dc_", HAND), ("ARAPlaybackRendererInterface", "pr_", {"addPlaybackRegion", "removePlaybackRegion"}), ("ARAEditorRendererInterface", "er_", set()), ("ARAEditorViewInterface", "ev_", set())]:
    ms = members(st)
    for n, args, ret in ms:
        if n in hand: continue
        a = ", ".join("_" + x for x in args)
        r = f" -> {ret}" if ret else ""
        out.append(f'unsafe extern "C" fn {pre}{n}({a}){r} {{ {default(n, ret)} }}\n'); count += 1
    out.append(f"pub(crate) static {pre.upper()}INTERFACE: SyncPtr<{st}> = SyncPtr({st} {{\n    structSize: std::mem::size_of::<{st}>(),\n")
    for n, _, _ in ms: out.append(f"    {n}: Some({pre}{n}),\n")
    out.append("});\n\n")
open(sys.argv[2], "w").write("".join(out)); print("stubs:", count)
assert count > 0
